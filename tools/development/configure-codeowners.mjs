import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const roleOptions = { lead: 'A', desktop: 'B', models: 'C', tools: 'D', data: 'E' };
const handlePattern = /^[a-zA-Z0-9](?:[a-zA-Z0-9]|-(?=[a-zA-Z0-9])){0,38}$/;

// Ownership is generated from the same manifest as the architecture guard.
// 审查归属和架构守卫使用同一份清单，避免两套目录负责人逐渐漂移。
export function buildCodeowners(manifest, roleHandles) {
  for (const role of Object.values(roleOptions)) {
    if (!handlePattern.test(roleHandles[role] ?? '')) throw new Error(`A valid GitHub login is required for role ${role}.`);
  }
  const lead = `@${roleHandles.A}`;
  const ownersFor = role => [...new Set([lead, `@${roleHandles[role]}`])].join(' ');
  const lines = [
    '# Generated by tools/development/configure-codeowners.mjs; role A coordinates integration.',
    '# 由同一份模块主责清单生成，A 协调整体集成。',
    '# A domain owner OR the lead can approve; this does not require both approvals.',
    '# 领域负责人或队长其中一人的批准即可，不表示 GitHub 强制两人同时批准。',
    `* ${lead}`
  ];
  const rules = [...manifest.ownershipRules, ...manifest.developmentEntrypoints];
  for (const rule of rules) {
    const owners = ownersFor(rule.role);
    if (rule.files) {
      for (const file of rule.files) lines.push(`/${file} ${owners}`);
    } else if (rule.directory) {
      for (const extension of rule.extensions) lines.push(`/${rule.directory}/*${extension} ${owners}`);
    } else if (rule.prefix) {
      // A generic domain directory includes its documentation; project-file overrides follow it.
      // 领域目录包含配套说明文件；工程文件的专属规则按清单顺序覆盖前面的领域规则。
      if (rule.extensions?.includes('.csproj')) lines.push(`/${rule.prefix}**/*.csproj ${owners}`);
      else lines.push(`/${rule.prefix} ${owners}`);
    } else throw new Error('An ownership rule has no supported path.');
  }
  // Last matching rules win in CODEOWNERS, so governance files stay with the lead.
  // CODEOWNERS 后匹配的规则生效，因此协作配置最后明确归队长维护。
  for (const entry of ['/.github/', '/.agents/', '/AGENTS.md', '/docs/team/', '/tools/development/']) {
    lines.push(`${entry} ${lead}`);
  }
  return `${lines.join('\r\n')}\r\n`;
}

async function configureCodeowners(argv) {
  const roleHandles = {};
  let shouldWrite = false;
  for (let index = 0; index < argv.length; index++) {
    const argument = argv[index];
    if (argument === '--write') {
      if (shouldWrite) throw new Error('Duplicate --write option.');
      shouldWrite = true;
      continue;
    }
    const option = argument.slice(2);
    const role = Object.hasOwn(roleOptions, option) ? roleOptions[option] : undefined;
    const handle = argv[index + 1];
    if (!argument.startsWith('--') || !role || !handle || handle.startsWith('--')) {
      throw new Error('Usage: node configure-codeowners.mjs --lead LOGIN --desktop LOGIN --models LOGIN --tools LOGIN --data LOGIN [--write]');
    }
    if (Object.hasOwn(roleHandles, role)) throw new Error(`Duplicate owner for role ${role}.`);
    roleHandles[role] = handle;
    index++;
  }
  const manifest = JSON.parse(await readFile(resolve(repositoryRoot, 'docs/team/module-ownership.json'), 'utf8'));
  const content = buildCodeowners(manifest, roleHandles);
  if (!shouldWrite) {
    process.stdout.write(content);
    return;
  }
  const target = resolve(repositoryRoot, '.github/CODEOWNERS');
  await mkdir(dirname(target), { recursive: true });
  await writeFile(target, content, 'utf8');
  console.log('Updated .github/CODEOWNERS locally; no invitations, permission changes or pushes were performed.');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try { await configureCodeowners(process.argv.slice(2)); }
  catch (error) { console.error(error.message); process.exitCode = 1; }
}
