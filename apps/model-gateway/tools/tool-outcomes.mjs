const desktopObservations = new Set(['computer.apps', 'computer.windows', 'computer.read', 'computer.screenshot']);

/**
 * Operation semantics belong to the broker, never to model prose or a third-party annotation.
 * 操作语义由代理层决定，不依赖模型正文或第三方注解。
 */
export const isDesktopObservation = name => desktopObservations.has(name);

export function isObservationFailure(call, result) {
  if (!result?.isError || result.status === 'unknown' || result.code === 'TOOL_CANCELLED') return false;
  if (isDesktopObservation(call?.name))
    return ['DESKTOP_TIMEOUT', 'DESKTOP_TIMED_OUT', 'DESKTOP_READ_TIMEOUT', 'DESKTOP_NOT_RESPONDING',
      'DESKTOP_WINDOW_UNAVAILABLE', 'DESKTOP_TARGET_CHANGED', 'DESKTOP_CAPTURE_FAILED'].includes(result.code);
  // Browser metadata is generated by our connection adapter, not readOnlyHint from an arbitrary server.
  // 浏览器元信息由本机连接适配器生成，不相信任意服务的 readOnlyHint。
  return call?.name?.startsWith('mcp.') && result.browser?.readOnly === true &&
    ['MCP_TIMEOUT', 'MCP_CONNECTION_CLOSED', 'MCP_CONNECTION_LOST', 'MCP_TOOL_FAILED'].includes(result.code);
}
